# 시즌 1: 보물 점수 게임 업그레이드 존
#
# 이 파일은 아이가 주로 바꾸는 곳입니다.
# 처음에는 챕터에서 알려준 한 줄만 바꿔도 됩니다.


# =========================
# [챕터 1] 게임 시작 문장
# =========================
start_message = "모험 시작!"


# =========================
# [챕터 2] 주인공 대사
# =========================
hero_message = "보물을 찾자!"


# =========================
# [챕터 3] 주인공 이름
# =========================
hero_name = "번개용사"


# =========================
# [챕터 4] 시작 점수
# =========================
start_score = 10


# =========================
# [챕터 5] 점수 변수
# =========================
score = start_score


# =========================
# [챕터 6] 체력
# =========================
hp = 100


# =========================
# [챕터 7] 이동 속도
# =========================
speed = 5


# =========================
# [챕터 8] 글자 합체
# =========================
title = hero_name + " 등장!"


# =========================
# [챕터 9] 멋진 상태창
# =========================
status_text = f"{hero_name} 점수: {score}"


# =========================
# [챕터 10] 더하기 마법
# 게임 기계가 쓰는 포장지입니다.
# 오늘은 가운데 한 줄만 보면 됩니다.
# =========================
treasure_point = 10


def upgrade_score_when_get_treasure(current_score):
    new_score = current_score + treasure_point
    return new_score


# =========================
# [챕터 11] 빼기 마법
# 오늘은 가운데 한 줄만 보면 됩니다.
# =========================
trap_damage = 20


def upgrade_hp_when_hit_trap(current_hp):
    new_hp = current_hp - trap_damage
    return new_hp


# =========================
# [챕터 12] 보너스 점수
# 오늘은 가운데 한 줄만 보면 됩니다.
# =========================
bonus_multiplier = 2


def upgrade_score_when_get_bonus(current_score):
    new_score = current_score * bonus_multiplier
    return new_score
